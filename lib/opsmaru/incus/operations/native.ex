defmodule Opsmaru.Incus.Operations.Native do
  @moduledoc """
  The native Incus client operations: one operation per verified client method.

  `openapi/0` returns them as a `tama-operations/1` document, source
  `opsmaru_incus_native`. It is generated by `mix opsmaru.incus.native` from
  the verified method registry into `priv/incus/native-operations.json` and
  read here at compile time, so nothing is parsed at runtime. Operation IDs
  are `incus_native_<snake_method>`. `unavailable/0` lists every client method
  that is not exported, with its reason: an interactive channel, a binary
  transfer, a call that selects another backend or carries credentials, or
  missing evidence.

  Native operations use their own scopes (`scopes/0`), which the composite
  scopes never imply. Every `DELETE` and `PUT` is destructive and requires
  `confirm` to repeat its target.

  `run/3` executes one operation in the caller's process with the same trust
  model as `Opsmaru.Incus.Operations.Composite.run/3`:

  1. the operation must be exported;
  2. the host-verified `:scopes` must include its scope;
  3. input must match the input schema and byte bound;
  4. a destructive operation requires `confirm` to equal its target;
  5. restricted `body.config` and `body.devices` need the host's
     `allow_restricted?/3`, by the composite rules;
  6. the host's `binding/2` and `authorize/3` must succeed.

  Only then does it make exactly one `Opsmaru.Incus.call/4`. A denial at any
  step makes no backend request. A background operation returns its native
  operation identity without being waited on, and a response lost after the
  request may have been accepted is reported as `uncertain`; nothing is
  retried. Success through this module is never client evidence.
  """
  alias Opsmaru.Incus
  alias Opsmaru.Incus.{Error, Response}
  alias Opsmaru.Incus.Operations.Composite.Instances
  alias Opsmaru.Incus.Operations.{Result, Runner}

  @path Path.expand("../../../../priv/incus/native-operations.json", __DIR__)
  @external_resource @path

  generated = Jason.decode!(File.read!(@path))

  @document put_in(generated["document"], ["info", "version"], Mix.Project.config()[:version])
  @unavailable generated["unavailable"]
  @components @document["components"]["schemas"]

  # What `run/3` needs of each operation.
  @operations Map.new(@document["paths"], fn {_, %{"post" => operation}} ->
                {operation["operationId"],
                 %{
                   scope: hd(operation["x-tama-scopes"]),
                   input: operation["requestBody"]["content"]["application/json"]["schema"],
                   native: operation["x-opsmaru-native"],
                   max_input: operation["x-tama-bounds"]["max_input_bytes"],
                   max_output: operation["x-tama-bounds"]["max_output_bytes"]
                 }}
              end)

  @scopes ~w(incus.native.read incus.native.write incus.native.delete incus.native.admin)

  @doc "The four scopes native operations require. Composite scopes never imply them."
  def scopes, do: @scopes

  @doc """
  The exported native operations as a `tama-operations/1` document, source
  `opsmaru_incus_native`: plain JSON-safe data, the same on every call for a
  release. Its `200` response is the native envelope `{kind, metadata?, etag?,
  operation_id?, operation?}` and `default` is the shared error object.
  `run/3` is the executor: a host returns its `{:ok, result}` as the `200`
  result and wraps the map of its `{:error, error}` as `{"error": error}`.
  """
  def openapi, do: @document

  @doc "Client methods that are not exported, with the exclusion rule and reason."
  def unavailable, do: @unavailable

  @doc """
  Run an exported native operation. Options (all host-supplied, never tool
  input):

    * `:host` - module implementing `Opsmaru.Incus.Operations.Host`;
    * `:caller` - the host's authenticated caller term;
    * `:scopes` - the caller's verified scopes.

  Returns `{:ok, envelope}` or `{:error, %{"kind" => ..., "message" => ...}}`.
  """
  def run(name, input, opts) when is_binary(name) and is_list(opts) do
    case Map.fetch(@operations, name) do
      {:ok, operation} -> execute(name, operation, input, opts)
      :error -> Result.error("unknown_operation", "no exported native operation has this name")
    end
  end

  defp execute(name, operation, input, opts) do
    host = Keyword.get(opts, :host)
    caller = Keyword.get(opts, :caller)

    with :ok <- Runner.scope(operation.scope, Keyword.get(opts, :scopes)),
         :ok <- Runner.validate(operation.input, input, operation.max_input, @components),
         :ok <- confirm(operation.native["confirm"], input),
         :ok <- Runner.restricted(restricted(input["body"]), host, caller, name),
         {:ok, binding} <- Runner.binding(host, caller, name),
         :ok <- Runner.authorize(host, caller, name, input),
         {:ok, client} <- Runner.client(binding),
         {:ok, client} <- Runner.project(client, input) do
      call(client, operation, input)
    end
  end

  defp confirm(nil, _input), do: :ok

  defp confirm(target, input) do
    expected =
      case target do
        %{"param" => param} -> input[param]
        %{"value" => value} -> value
      end

    if is_binary(expected) and input["confirm"] === expected,
      do: :ok,
      else:
        Result.error(
          "confirmation_mismatch",
          "set confirm to #{inspect(expected)} to confirm this destructive operation"
        )
  end

  # The composite restricted-config rules, applied to any body config or devices.
  defp restricted(%{} = body) do
    Instances.restricted(%{
      "config" => map(body["config"]) |> Map.merge(map(body["Config"])),
      "devices" => map(body["devices"]) |> Map.merge(map(body["Devices"]))
    })
  end

  defp restricted(_), do: []

  defp map(%{} = map), do: map
  defp map(_), do: %{}

  # Exactly one native request. Nothing is waited on or resent.
  defp call(client, operation, input) do
    native = operation.native

    opts =
      for {key, field} <- [body: "body", etag: "etag"], value = input[field], do: {key, value}

    case Incus.call(client, native["method"], Map.take(input, native["params"]), opts) do
      {:ok, %Response{} = response} ->
        response |> envelope(native["result"]) |> Result.within(operation.max_output)

      {:error, %Error{} = error} ->
        Result.client_error(error)

      {:error, other} ->
        Result.client_error(other)
    end
  end

  defp envelope(response, "operation"),
    do: %{
      "kind" => "operation",
      "operation_id" => Result.operation_id(response.operation),
      "operation" => Result.native(response)
    }

  defp envelope(response, "empty_sync"), do: etag(%{"kind" => "empty_sync"}, response)

  defp envelope(response, kind) when kind in ["list", "grouped_list"],
    do:
      etag(
        %{"kind" => kind, "metadata" => Enum.map(response.metadata, &Result.native/1)},
        response
      )

  defp envelope(%Response{metadata: nil} = response, "sync"),
    do: etag(%{"kind" => "sync"}, response)

  defp envelope(response, kind),
    do: etag(%{"kind" => kind, "metadata" => Result.native(response)}, response)

  defp etag(envelope, %Response{etag: etag}) when is_binary(etag) and etag != "",
    do: Map.put(envelope, "etag", etag)

  defp etag(envelope, _), do: envelope
end
